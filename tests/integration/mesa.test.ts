// ---- distribution ---------------------------------------------------------------

test('6+7+8+10. exactly 8 Previews, 4 Medium, 4 Unexpected, deterministic order', () => {
  const obs = runMesaExploration(src(), DEFAULT_MESA_STATE, 1000);
  assert.equal(obs.length, 8);
  assert.equal(obs.filter((o) => o.territory === 'medium').length, 4);
  assert.equal(obs.filter((o) => o.territory === 'unexpected').length, 4);
  assert.deepEqual(obs.slice(0, 4).map((o) => o.territory), ['medium', 'medium', 'medium', 'medium']);
  assert.deepEqual(obs.slice(4).map((o) => o.territory), ['unexpected', 'unexpected', 'unexpected', 'unexpected']);
  const obs2 = runMesaExploration(src(), DEFAULT_MESA_STATE, 1000);
  assert.deepEqual(obs.map((o) => o.strategyId), obs2.map((o) => o.strategyId), 'ordering is deterministic');
});

test('9. no Preview is the unmodified source', () => {
  const bytes = src();
  const sourceHash = contentHash(bytes);
  const obs = runMesaExploration(bytes, DEFAULT_MESA_STATE, 1000);
  for (const o of obs) assert.notEqual(contentHash(o.bytes), sourceHash);
});

