test('1+2+3. MesaState validates and clamps all eight controls', () => {
  const state = validateMesaState({
    fragmentar: { escala: -20, desorden: 150 }, acelerar: { tiempo: 50.6, movimiento: -1 },
    microscopio: { zoom: 200, persistencia: 0 }, excitar: { energia: 100, estabilidad: -50 },
  });
  assert.equal(state.fragmentar.escala, 0, 'below 0 clamps to 0');
  assert.equal(state.fragmentar.desorden, 100, 'above 100 clamps to 100');
  assert.equal(state.acelerar.movimiento, 0);
  assert.equal(state.microscopio.zoom, 100);
  assert.equal(state.excitar.estabilidad, 0);
  assert.ok(Number.isInteger(state.acelerar.tiempo), 'values round to integers');
});

