// ---- lifecycle / provenance ---------------------------------------------------------

async function lab() {
  const dir = mkdtempSync(join(tmpdir(), 'spk-mesa-'));
  const records = new SqliteRecordStore(join(dir, 'store.sqlite'), CURRENT_SCHEMA);
  await migrate(records);
  const content = new FsContentStore(join(dir, 'content'));
  const registry = new DataRegistry();
  registerAlchemyVocabulary(registry);
  const service = new AlchemyService(records, content, registry);
  const queries = new AlchemyQueries(records, content);
  const artist = await service.registerAgent({ kind: 'human', name: 'artist', version: '1' });
  return { records, content, service, queries, artist };
}

test('29+36. Mesa Preview generation persists no Material; siblings remain nonpersistent', async () => {
  const { COLLECTIONS } = await import('../../src/core/primitives.ts');
  const materialCount = async () => (await l.records.scan(COLLECTIONS.entities, null, 500)).items
    .filter((e) => (e as { role?: string }).role === 'material').length;
  const l = await lab();
  const source = await l.service.importMaterial({ bytes: src(3), filename: 's.wav', agentId: l.artist.id });
  const intent = await l.service.createResearchIntent({ question: 'q', agentId: l.artist.id });
  const before = await materialCount();
  // Running the exploration legitimately creates one Experiment Entity (as
  // fragment-exploration-v1 already does) -- the claim under test is about
  // Materials specifically: eight Previews, zero new Materials.
  await l.service.runMesaExploration({
    materialId: source.id, researchIntentId: intent.id, mesaState: DEFAULT_MESA_STATE, baseSeed: 1, agentId: l.artist.id });
  const after = await materialCount();
  assert.equal(after, before, 'eight Previews, zero new Materials');
  await l.records.close();
});

test('30+31+32+33+34+35. Retain records complete Mesa provenance', async () => {
  const l = await lab();
  const source = await l.service.importMaterial({ bytes: src(3), filename: 's.wav', agentId: l.artist.id });
  const intent = await l.service.createResearchIntent({ question: 'q', agentId: l.artist.id });
  const set = await l.service.runMesaExploration({
    materialId: source.id, researchIntentId: intent.id, mesaState: DEFAULT_MESA_STATE, baseSeed: 7, agentId: l.artist.id });
  const chosen = set.variations.find((v) => v.territory === 'unexpected')!;
  const r = await l.service.retain(chosen.preview, l.artist.id);
  assert.equal(r.created, true, 'exactly one Material created');
  assert.equal(r.material.attributes.configurationId, MESA_CONFIGURATION_ID);
  assert.equal(r.material.attributes.configurationVersion, MESA_VERSION);
  const p = r.material.attributes.parameters as Record<string, unknown>;
  assert.deepEqual(p.mesaState, DEFAULT_MESA_STATE);
  assert.equal(p.territory, chosen.territory);
  assert.equal(p.strategyId, chosen.strategyId);
  assert.equal(p.anchor, chosen.anchor);
  await l.records.close();
});

test('37+38+39. retained Mesa output can be explored again; genealogy and lineage color root are correct', async () => {
  const l = await lab();
  const source = await l.service.importMaterial({ bytes: src(3), filename: 's.wav', agentId: l.artist.id });
  const intent = await l.service.createResearchIntent({ question: 'q', agentId: l.artist.id });
  const set1 = await l.service.runMesaExploration({
    materialId: source.id, researchIntentId: intent.id, mesaState: DEFAULT_MESA_STATE, baseSeed: 11, agentId: l.artist.id });
  const b = await l.service.retain(set1.variations[4].preview, l.artist.id); // first Unexpected
  await l.service.promote(b.material.id, l.artist.id);

  const set2 = await l.service.runMesaExploration({
    materialId: b.material.id, researchIntentId: intent.id, mesaState: DEFAULT_MESA_STATE, baseSeed: 22, agentId: l.artist.id });
  assert.equal(set2.variations.length, 8, 'a retained Mesa output is a valid Mesa input');
  const c = await l.service.retain(set2.variations[0].preview, l.artist.id);

  const ancestors = await l.queries.ancestors(c.material.id);
  assert.deepEqual(ancestors.nodes.map((n) => n.id), [b.material.id, source.id], 'genealogy A -> B -> C');

  const { resolveLineageRoot } = await import('../../src/domain/alchemy/lineage.ts');
  const resolved = await resolveLineageRoot(c.material.id, l.queries);
  assert.equal(resolved.rootId, source.id, 'lineage color root remains the original import');
  await l.records.close();
});

// ---- cross-source behavior -----------------------------------------------------------

test('40+41+42. unrelated sources do not collapse toward identical Unexpected outputs', () => {
  const a = src(3, 4000), b = src(77, 4000);
  const obsA = runMesaExploration(a, DEFAULT_MESA_STATE, 1000);
  const obsB = runMesaExploration(b, DEFAULT_MESA_STATE, 1000);
  let collapsed = 0;
  for (let i = 0; i < 8; i++) if (contentHash(obsA[i].bytes) === contentHash(obsB[i].bytes)) collapsed += 1;
  assert.equal(collapsed, 0, 'no strategy produces byte-identical output across unrelated sources');

  // Even at extreme MesaState, source-derived anchors keep provenance distinct.
  const extreme = {
    fragmentar: { escala: 100, desorden: 100 }, acelerar: { tiempo: 100, movimiento: 100 },
    microscopio: { zoom: 100, persistencia: 100 }, excitar: { energia: 100, estabilidad: 100 },
  };
  const obsAe = runMesaExploration(a, extreme, 1000);
  const obsBe = runMesaExploration(b, extreme, 1000);
  let collapsedExtreme = 0;
  for (let i = 0; i < 8; i++) if (contentHash(obsAe[i].bytes) === contentHash(obsBe[i].bytes)) collapsedExtreme += 1;
  assert.equal(collapsedExtreme, 0, 'no collapse even at maximum intensity on every control');
});

