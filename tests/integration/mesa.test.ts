// ---- audio safety -----------------------------------------------------------------

test('22+24+25. frames stay channel-aligned, no clipping, silence is safe', () => {
  const silent = encodeWav({ sampleRate: 8000, channels: 1, samples: new Int16Array(2000) });
  const obs = runMesaExploration(silent, DEFAULT_MESA_STATE, 1);
  assert.equal(obs.length, 8);
  for (const o of obs) {
    const audio = decodeWav(o.bytes);
    assert.equal(audio.samples.length % audio.channels, 0, 'sample count is frame-aligned');
    for (const s of audio.samples) assert.ok(Math.abs(s) < 32768);
    assert.ok(Number.isFinite(audio.samples[0] ?? 0));
  }
});

