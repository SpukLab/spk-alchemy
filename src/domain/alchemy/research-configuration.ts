/** New explorations default to the latest configuration version. */
export const DEFAULT_FRAGMENT_EXPLORATION = FRAGMENT_EXPLORATION_V1_2;

export const BUILT_IN_CONFIGURATIONS: readonly ResearchConfiguration[] = [
  FRAGMENT_EXPLORATION_V1, FRAGMENT_EXPLORATION_V1_1, FRAGMENT_EXPLORATION_V1_2,
];

const DEFAULT_VERSION_BY_ID = new Map<string, ResearchConfiguration>([
  [DEFAULT_FRAGMENT_EXPLORATION.id, DEFAULT_FRAGMENT_EXPLORATION],
]);

/**
 * Resolve a configuration by id, optionally pinned to an exact version.
 * Omitting version returns the current default — this is how new explorations
 * pick up 1.1.0 without call sites needing to know a version exists. An old
 * manifest that recorded "1.0.0" must always pass its version explicitly, so
 * replay resolves the exact configuration that produced it, not the default.
 */
export function configurationById(id: string, version?: string): ResearchConfiguration {
  const candidates = BUILT_IN_CONFIGURATIONS.filter((c) => c.id === id);
  if (candidates.length === 0) throw new Error(`unknown research configuration: ${id}`);
  if (version) {
    const exact = candidates.find((c) => c.version === version);
    if (!exact) throw new Error(`unknown research configuration version: ${id}@${version}`);
    return exact;
  }
  return DEFAULT_VERSION_BY_ID.get(id) ?? candidates[candidates.length - 1]!;
}

export function describeParameters(seed: number, totalFrames: number): DerivedParameters {
  return deriveParameters(seed, totalFrames);
}
