import type { AudioBuffer } from '../../audio/wav.ts';
import { decodeWav, encodeWav } from '../../audio/wav.ts';
import {
  seededRandom, fragmentEvenly, shuffleWithSeed, sliceFragment,
  reverseFrames, applyGain, silence, concatSamples, applyBoundaryFade,
} from '../../audio/operations.ts';

/**
 * ResearchConfiguration — a versioned domain configuration contract.
 *
 * It is NOT a canonical structural primitive and NOT a persistent Entity in
 * this phase. It is executable, versioned configuration; what persists on
 * Retain is its id, version, operation sequence, parameters and seed, recorded
 * in the resulting Material's provenance.
 *
 * A change to generated bytes is a new version, never a silent edit to an
 * existing one — see FRAGMENT_EXPLORATION_V1 (unchanged) and
 * FRAGMENT_EXPLORATION_V1_1 (adds Preview-level gain correction) below.
 */

export const RESEARCH_CONFIGURATION_SCHEMA_VERSION = 1;

export interface OperationStep {
  operation: string;
  description: string;
}

export interface ParameterRange {
  min: number;
  max: number;
  description: string;
}

export interface InputConstraints {
  requiredEncoding: 'pcm16-wav';
  minFrames: number;
  maxChannels: number;
}

export interface ResearchConfiguration {
  id: string;
  name: string;
  version: string;
  schemaVersion: number;
  implementationVersion: string;
  inputConstraints: InputConstraints;
  operations: readonly OperationStep[];
  parameterRanges: Readonly<Record<string, ParameterRange>>;
  defaultVariationCount: number;
  seedStrategy: 'base-plus-index';
  /** Derives each variation's seed from the base seed. Fully determined. */
  variationSeed: (baseSeed: number, index: number) => number;
  /** Deterministic transform: identical arguments always yield identical bytes. */
  render: (inputBytes: Uint8Array, seed: number) => Uint8Array;
}

/** Parameters chosen for one variation, recorded in provenance. */
export interface DerivedParameters {
  fragmentCount: number;
  reversedFragments: number[];
  silenceFrames: number;
  gainNumerator: number;
  gainDenominator: number;
  order: number[];
}

function deriveParameters(seed: number, totalFrames: number): DerivedParameters {
  const rng = seededRandom(seed);
  const fragmentCount = 3 + Math.floor(rng() * 6);          // 3..8
  const fragments = fragmentEvenly(totalFrames, fragmentCount);
  const indices = fragments.map((_, i) => i);
  const order = shuffleWithSeed(indices, rng);
  const reversedFragments = order.filter(() => rng() < 0.4);
  const silenceFrames = Math.floor(rng() * 800);            // 0..799
  const gainNumerator = 6 + Math.floor(rng() * 5);          // 6..10
  return {
    fragmentCount: fragments.length, reversedFragments,
    silenceFrames, gainNumerator, gainDenominator: 10, order,
  };
}

/**
 * Fragment-level shaping only: fragmenting, reordering, selective reversal,
 * spacing and a per-fragment gain that decays across position. Unchanged since
 * 1.0.0 — this is what gives each variation its internal dynamic character,
 * and the gain-consistency refinement in 1.1.0 must not touch it.
 */
function renderVariation(audio: AudioBuffer, seed: number): AudioBuffer {
  const frames = audio.samples.length / audio.channels;
  const params = deriveParameters(seed, frames);
  const fragments = fragmentEvenly(frames, params.fragmentCount);
  const reversed = new Set(params.reversedFragments);
  const gap = silence(params.silenceFrames, audio.channels);

  const parts: Int16Array[] = [];
  params.order.forEach((fragmentIndex, position) => {
    const fragment = fragments[fragmentIndex];
    if (!fragment) return;
    let piece = sliceFragment(audio, fragment);
    if (reversed.has(fragmentIndex)) piece = reverseFrames(piece, audio.channels);
    // Gain shaping decays across positions, so ordering is audible.
    const numerator = Math.max(3, params.gainNumerator - position);
    piece = applyGain(piece, numerator, params.gainDenominator);
    parts.push(piece);
    if (position < params.order.length - 1 && gap.length > 0) parts.push(gap);
  });

  return { ...audio, samples: concatSamples(parts) };
}

// ---- Preview-level gain correction (1.1.0) ---------------------------------

/**
 * Shared listening-level target for every Preview, independent of anything
 * else in its set. Measured against the 1.0.0 reference corpus (RMS spread
 * 0.067–0.133, ~6 dB): this sits near the middle of that range, so the
 * correction narrows the spread symmetrically rather than dragging everything
 * toward one extreme.
 */
export const PREVIEW_TARGET_RMS = 0.09;

/**
 * Fraction of the distance to the target that is actually applied. A full
 * snap-to-target (1.0) made every Preview measure identically — every one at
 * exactly PREVIEW_TARGET_RMS, a flat 0 dB spread — which is explicitly not the
 * goal: overall level is meant to become CONSISTENT, not IDENTICAL. Pulling
 * only partway narrows the reference-corpus spread from 6.0 dB to roughly
 * 2 dB while every Preview still measures audibly differently from its
 * siblings.
 */
export const PREVIEW_GAIN_PULL_STRENGTH = 0.65;

/** Bounded both directions: preserves character, narrows the range. */
export const PREVIEW_GAIN_MAX_BOOST_DB = 4;
export const PREVIEW_GAIN_MAX_CUT_DB = 4;

/** Safety margin under full scale, applied after the target correction. */
export const PREVIEW_PEAK_CEILING = 0.97;

const dbToLinear = (db: number): number => 10 ** (db / 20);
const linearToDb = (ratio: number): number => 20 * Math.log10(ratio);

export interface PreviewGainMeasurement {
  peak: number;
  rms: number;
  correction: number;
  correctionDb: number;
  clipped: boolean;
}

/** Peak and RMS of a completed buffer, in the same units the correction targets. */
export function measurePreviewLevel(samples: Int16Array): { peak: number; rms: number } {
  let peak = 0;
  let sumSquares = 0;
  for (const s of samples) {
    const v = s / 32768;
    const a = Math.abs(v);
    if (a > peak) peak = a;
    sumSquares += v * v;
  }
  const rms = samples.length > 0 ? Math.sqrt(sumSquares / samples.length) : 0;
  return { peak, rms };
}

/**
 * One deterministic global gain factor for a completed Preview.
 *
 * A pure function of that Preview's own samples: never derived from sibling
 * Previews in the same set, so generating one Preview alone or as part of
 * eight produces identical bytes. Bounded in both directions, then re-checked
 * against a peak ceiling so the correction itself can never introduce
 * clipping — the fragment-level dynamics stay exactly as shaped, this only
 * scales the whole result once.
 */
export function computePreviewGainCorrection(samples: Int16Array): number {
  const { peak, rms } = measurePreviewLevel(samples);
  if (rms === 0 || peak === 0) return 1; // silence: nothing to correct, no division by zero

  // Move only part of the way toward the target, in dB (perceptual, not linear)
  // so a small ideal correction and a large one are pulled by the same
  // proportion of the ear's sense of loudness.
  const idealDb = linearToDb(PREVIEW_TARGET_RMS / rms);
  let appliedDb = idealDb * PREVIEW_GAIN_PULL_STRENGTH;
  appliedDb = Math.min(PREVIEW_GAIN_MAX_BOOST_DB, Math.max(-PREVIEW_GAIN_MAX_CUT_DB, appliedDb));
  let correction = dbToLinear(appliedDb);

  const projectedPeak = peak * correction;
  if (projectedPeak > PREVIEW_PEAK_CEILING) {
    correction = PREVIEW_PEAK_CEILING / peak;
  }
  return correction;
}

function applyPreviewGainCorrection(samples: Int16Array): { samples: Int16Array; correction: number } {
  const correction = computePreviewGainCorrection(samples);
  if (correction === 1) return { samples, correction };
  const out = new Int16Array(samples.length);
  for (let i = 0; i < samples.length; i++) {
    out[i] = Math.max(-32768, Math.min(32767, Math.round(samples[i]! * correction)));
  }
  return { samples: out, correction };
}

function renderVariationV1_1(audio: AudioBuffer, seed: number): AudioBuffer {
  const raw = renderVariation(audio, seed);
  const { samples } = applyPreviewGainCorrection(raw.samples);
  return { ...raw, samples };
}

// ---- Slice-boundary micro-fade (1.2.0) -------------------------------------

/**
 * Short deterministic fade around fragment/silence splice boundaries, to
 * remove the discontinuity clicks measured at those cut points without
 * smearing rhythm or shifting timing. Sample-rate independent in perceptual
 * duration: 5ms converts to ~221 frames at 44.1kHz, exactly 240 at 48kHz.
 */
export const PREVIEW_BOUNDARY_FADE_MS = 5;

export function fadeFramesForSampleRate(
  sampleRateHz: number, fadeMs: number = PREVIEW_BOUNDARY_FADE_MS,
): number {
  return Math.round((sampleRateHz * fadeMs) / 1000);
}

/**
 * Same fragment shaping and gain-consistency correction as 1.1.0, with one
 * addition in between: every non-silence piece fades out unless it is the
 * very last element of the Preview, and fades in unless it is the very first.
 * That single rule covers all three boundary shapes without special cases —
 * fragment-to-fragment fades both sides, fragment-to-silence fades only the
 * outgoing fragment (never the silence itself), silence-to-fragment fades
 * only the incoming fragment. The natural start and end of the whole Preview
 * are never faded: they are not artificial splices.
 */
function renderVariationV1_2(audio: AudioBuffer, seed: number): AudioBuffer {
  const frames = audio.samples.length / audio.channels;
  const params = deriveParameters(seed, frames);
  const fragments = fragmentEvenly(frames, params.fragmentCount);
  const reversed = new Set(params.reversedFragments);
  const gap = silence(params.silenceFrames, audio.channels);
  const configuredFade = fadeFramesForSampleRate(audio.sampleRate);

  const parts: Int16Array[] = [];
  const isGap: boolean[] = [];
  params.order.forEach((fragmentIndex, position) => {
    const fragment = fragments[fragmentIndex];
    if (!fragment) return;
    let piece = sliceFragment(audio, fragment);
    if (reversed.has(fragmentIndex)) piece = reverseFrames(piece, audio.channels);
    const numerator = Math.max(3, params.gainNumerator - position);
    piece = applyGain(piece, numerator, params.gainDenominator);
    parts.push(piece);
    isGap.push(false);
    if (position < params.order.length - 1 && gap.length > 0) {
      parts.push(gap);
      isGap.push(true);
    }
  });

  for (let i = 0; i < parts.length; i++) {
    if (isGap[i]) continue; // silence itself is never faded
    const fadeIn = i > 0 ? configuredFade : 0;
    const fadeOut = i < parts.length - 1 ? configuredFade : 0;
    if (fadeIn === 0 && fadeOut === 0) continue;
    parts[i] = applyBoundaryFade(parts[i]!, audio.channels, fadeIn, fadeOut);
  }

  const raw = { ...audio, samples: concatSamples(parts) };
  const { samples } = applyPreviewGainCorrection(raw.samples);
  return { ...raw, samples };
}

